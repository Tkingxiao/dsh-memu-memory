import { build } from 'esbuild'
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'

const packages = ['d3-force', 'd3-dispatch', 'd3-quadtree', 'd3-timer']
const licenses = packages.map(name => `${name}\n${fs.readFileSync(new URL(`../node_modules/${name}/LICENSE`, import.meta.url), 'utf8')}`).join('\n\n')
await build({
  entryPoints: [fileURLToPath(new URL('../lib/webui/graph-view.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../lib/webui/graph-view.bundle.js', import.meta.url)),
  bundle: true,
  format: 'iife',
  globalName: 'DshMemuGraph',
  target: ['es2020'],
  minify: true,
  banner: { js: '/* Generated by scripts/build-graph.mjs. Licenses: graph-LICENSE.txt */' },
})
fs.writeFileSync(new URL('../lib/webui/graph-LICENSE.txt', import.meta.url), licenses)
