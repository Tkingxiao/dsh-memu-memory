import { build } from 'esbuild'
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'

// 引擎已改为自研力导向，bundle 里不再打包任何第三方运行时代码。
await build({
  entryPoints: [fileURLToPath(new URL('../lib/webui/graph-view.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../lib/webui/graph-view.bundle.js', import.meta.url)),
  bundle: true,
  format: 'iife',
  globalName: 'DshMemuGraph',
  target: ['es2020'],
  minify: true,
  banner: { js: '/* Generated by scripts/build-graph.mjs. Licenses: graph-LICENSE.txt */' },
})
fs.writeFileSync(new URL('../lib/webui/graph-LICENSE.txt', import.meta.url),
  'graph-view.bundle.js: 本 bundle 无第三方运行时依赖（自研力导向引擎）。\n')
