import fs from 'node:fs'
import { fileURLToPath } from 'node:url'

// 引擎已改为自研力导向，bundle 里不再打包任何第三方运行时代码。
// esbuild 只在这里用，而且是 devDependency：静态 import 会让从 npm 装出来的插件
// 目录里的 `npm run check` 直接崩在模块解析，到不了下面的 skip 分支。
const target = fileURLToPath(new URL('../lib/webui/graph-view.bundle.js', import.meta.url))
const shared = {
  entryPoints: [fileURLToPath(new URL('../lib/webui/graph-view.js', import.meta.url))],
  bundle: true,
  format: 'iife',
  globalName: 'DshMemuGraph',
  target: ['es2020'],
  minify: true,
  banner: { js: '/* Generated by scripts/build-graph.mjs. Licenses: graph-LICENSE.txt */' },
}

const esbuild = await (async () => {
  try { return (await import('esbuild')).build } catch { return null }
})()

// `--check` 是防漂移闸门：改完引擎忘了重打包，浏览器加载的还是旧 bundle，
// 源码里的修复（比如最小缩放打架）在真实页面上根本不存在，测试却全绿。
if (process.argv.includes('--check')) {
  if (!esbuild) {
    console.log('skip graph bundle check: esbuild is not installed (production install has no devDependencies)')
    process.exit(0)
  }
  // write:false：产物只在内存里比对，不在磁盘上留一份「看似 bundle」的副本。
  const result = await esbuild({ ...shared, write: false })
  const drifted = Buffer.from(result.outputFiles[0].text, 'utf8').equals(fs.readFileSync(target)) === false
  if (drifted) {
    console.error('lib/webui/graph-view.bundle.js does not match lib/webui/graph-view.js — run `npm run build:graph`')
    process.exit(1)
  }
  process.exit(0)
}

if (!esbuild) {
  console.error('esbuild is required to build the graph bundle: `npm ci` in the plugin directory first')
  process.exit(1)
}
await esbuild({ ...shared, outfile: target })
fs.writeFileSync(new URL('../lib/webui/graph-LICENSE.txt', import.meta.url),
  'graph-view.bundle.js: 本 bundle 无第三方运行时依赖（自研力导向引擎）。\n')
