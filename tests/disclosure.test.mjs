const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-memu-memory-tone-'))
process.env.DSH_MEMU_HOME = home

const state = await import('../lib/state.js')
const memory = await import('../lib/memory.js')
const inject = await import('../lib/inject.js')

test.after(() => {
  try { fs.rmSync(home, { recursive: true, force: true }) } catch {}
})

function execFor(sessionId, cwd) {
  return { agent: { session: { header: { id: sessionId, cwd, agentPreset: 'coding' } } } }
}

function seedGlobal(id, patch) {
  const index = state.loadGlobalIndex()
  index.entries[id] = {
    track: 'memory',
    layer: 'long_term',
    domain: 'coding',
    status: 'active',
    confidence: 0.9,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    ...patch,
  }
  state.saveGlobalIndex(index)
}

test('disclosure changes the wording of the injected line, not whether it arrives', async () => {
  const cwd = path.join(home, 'proj-tone')
  const sessionId = 'tone-suffix'
  state.ensureSession(sessionId, { cwd, agentPreset: 'coding' })
  const exec = execFor(sessionId, cwd)
  const settings = { ...state.getSettings(), relevanceThreshold: 0, privateTopK: 5 }

  await memory.privateRemember({ exec, content: 'The ledger file lives in docs/ledger.md.', title: 'ledger file', disclosure: 'can_tell' })
  await memory.privateRemember({ exec, content: 'The ledger file is generated by the old importer.', title: 'ledger importer', disclosure: 'only_if_asked' })
  await memory.privateRemember({ exec, content: 'The ledger file was named after his father.', title: 'ledger name', disclosure: 'never_say' })

  const recall = await inject.buildRecall(state.getSessionBinding(sessionId), 'ledger file', 1, settings, exec, sessionId)
  assert.deepEqual(recall.errors, [])
  assert.ok(recall.text.includes('ledger file'), 'a can_tell memory arrives as before')
  assert.equal(recall.text.split('对方不问就别主动提').length - 1, 1, 'only_if_asked carries its suffix')
  assert.equal(recall.text.split('记得，但别直接说出口').length - 1, 1, 'never_say carries its suffix')
  // The default case must stay silent: adding a suffix to every line would be noise.
  const canTellLine = recall.text.split('\n').find((line) => line.includes('ledger file ·') || line.includes('ledger file'))
  assert.ok(canTellLine && !canTellLine.includes('对方不问') && !canTellLine.includes('别直接说出口'))
})

test('a secret stays out of the anchor but is still reachable through recall', async () => {
  const cwd = path.join(home, 'proj-secret')
  const sessionId = 'tone-secret'
  const binding = state.ensureSession(sessionId, { cwd, agentPreset: 'coding' })
  const exec = execFor(sessionId, cwd)
  const settings = { ...state.getSettings(), anchorTokens: 700, relevanceThreshold: 0 }

  const { id: secretId } = await memory.privateRemember({
    exec,
    content: 'SECRET-BODY he is planning to leave the company in spring.',
    title: 'leaving in spring',
    visibility: 'secret',
  })
  const { id: pinnedSecretId } = await memory.privateRemember({
    exec,
    content: 'PINNED-SECRET-BODY the diagnosis he told nobody else.',
    title: 'the diagnosis',
    layer: 'must_remember',
    pinReason: 'he said it once and never again',
    pinSource: 'user_explicit',
    visibility: 'secret',
  })
  const { id: sharedId } = await memory.privateRemember({
    exec,
    content: 'SHARED-BODY the deploy window is Thursday night.',
    title: 'deploy window',
  })

  const anchor = inject.buildAnchor(binding, settings)
  // The anchor is the most conspicuous list the model sees every turn; a secret that
  // sits there is a secret waiting to be said at the wrong moment.
  assert.equal(anchor.text.includes('SECRET-BODY'), false)
  assert.equal(anchor.text.includes('PINNED-SECRET-BODY'), false, 'pinning does not override secrecy')
  assert.equal(anchor.text.includes(secretId), false)
  assert.equal(anchor.text.includes(pinnedSecretId), false)
  assert.ok(anchor.text.includes('SHARED-BODY'), 'ordinary memories still show up')

  const recalled = await memory.privateRecall({ exec, query: 'leave company diagnosis deploy window', topK: 5, relevanceThreshold: 0 })
  assert.ok(recalled.files.some((file) => file.name === secretId), 'a secret is a recall target, not a hidden row')
  assert.ok(recalled.files.some((file) => file.name === sharedId))
})

